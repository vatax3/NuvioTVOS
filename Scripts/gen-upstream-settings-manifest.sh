#!/bin/sh
# Regenerates Sources/Data/Sync/UpstreamSettingsManifest.swift from the Android app's DataStore
# sources at a given tag: every preference key the settings blob can carry, with the feature it
# belongs to and its DataStore type.
#
# Why a generated table rather than a hand-written one: the Android app reads its preferences
# through typed keys, and a value of the wrong type under a key it knows throws on read. So the
# type of every key this app pushes must be the one upstream declares, and the only list of
# those that stays true is the source itself. Rerun it on every parity pass:
#
#   Scripts/gen-upstream-settings-manifest.sh 1.1.0-beta.11
#
# Needs `gh` signed in and python3.
set -eu

TAG="${1:?usage: $0 <upstream tag>}"
REPO="NuvioMedia/NuvioTV"
DIR="app/src/main/java/com/nuvio/tv/data/local"
OUT="$(cd "$(dirname "$0")/.." && pwd)/Sources/Data/Sync/UpstreamSettingsManifest.swift"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

gh api "repos/$REPO/contents/$DIR?ref=$TAG" --jq '.[] | select(.name | endswith(".kt")) | .name' |
while read -r name; do
    gh api "repos/$REPO/contents/$DIR/$name?ref=$TAG" --jq .content | base64 -d > "$WORK/$name"
done

python3 - "$WORK" "$TAG" "$OUT" <<'PY'
import os, re, sys
work, tag, out = sys.argv[1:4]
# The features the settings blob carries (upstream's `syncedFeatures`).
synced = {"theme_settings", "layout_settings", "experience_settings", "player_settings",
          "stream_badge_settings", "plugin_settings", "trailer_settings", "tmdb_settings",
          "mdblist_settings", "trakt_settings", "debrid_settings", "animeskip_settings",
          "track_preference"}
types = {"boolean": "boolean", "int": "int", "long": "long", "float": "float",
         "double": "double", "string": "string", "stringSet": "stringSet"}
key_re = re.compile(r'\b(boolean|int|long|float|double|string|stringSet)PreferencesKey\(\s*"([^"$]+)"\s*\)')
feature_re = re.compile(r'(?:const val|val)\s+FEATURE\s*=\s*"([^"]+)"')
entries = {}
for name in sorted(os.listdir(work)):
    text = open(os.path.join(work, name), encoding="utf-8").read()
    match = feature_re.search(text)
    if not match or match.group(1) not in synced:
        continue
    feature = match.group(1)
    for kind, key in key_re.findall(text):
        entries.setdefault((feature, key), types[kind])

lines = [
    "// Generated by Scripts/gen-upstream-settings-manifest.sh from NuvioMedia/NuvioTV " + tag + ".",
    "// Do not edit by hand: rerun the script on each parity pass.",
    "",
    "enum UpstreamSettingsManifest {",
    "    static let tag = \"" + tag + "\"",
    "",
    "    /// feature → key → DataStore type.",
    "    static let keys: [String: [String: SettingsBlobType]] = [",
]
by_feature = {}
for (feature, key), kind in entries.items():
    by_feature.setdefault(feature, []).append((key, kind))
for feature in sorted(by_feature):
    lines.append("        \"" + feature + "\": [")
    for key, kind in sorted(by_feature[feature]):
        lines.append("            \"" + key + "\": ." + kind + ",")
    lines.append("        ],")
lines += ["    ]", "}", ""]
open(out, "w", encoding="utf-8").write("\n".join(lines))
print("wrote", sum(len(v) for v in by_feature.values()), "keys in", len(by_feature), "features to", out)
PY
